// ------------------------------------------
// Завдання 1: Перевірка парності
// ------------------------------------------
// Виводимо заголовок першого завдання у консоль
console.log("--- Завдання 1: Перевірка парності ---");

// Оголошуємо змінну number та присвоюємо їй число для перевірки
let number = 14; 

// Перевіряємо за допомогою конструкції if...else, чи є число парним:
// Оператор % повертає залишок від ділення (14 % 2 = 0)
// Строге порівняння === 0 перевіряє, чи залишок дорівнює нулю
if (number % 2 === 0) {
    // Цей блок коду виконується, якщо умова істинна (true) — число парне
    console.log("Число парне");
} else {
    // Цей блок коду виконується, якщо умова хибна (false) — число непарне
    console.log("Число непарне");
}


// ------------------------------------------
// Завдання 2: Система знижок
// ------------------------------------------
// Виводимо заголовок другого завдання (з відступом \n)
console.log("\n--- Завдання 2: Система знижок ---");

// Оголошуємо змінну purchaseAmount для збереження суми покупки
let purchaseAmount = 750; 

// 1-ша перевірка: чи сума покупки більша або дорівнює 1000
if (purchaseAmount >= 1000) {
    // Виводиться знижка 10%, якщо сума від 1000 і більше
    console.log("Ваша знижка 10%");
} 
// 2-га перевірка: якщо перша умова false, перевіряємо чи сума >= 500 (діапазон 500-999)
else if (purchaseAmount >= 500) {
    // Виводиться знижка 5%, якщо сума від 500 до 999
    console.log("Ваша знижка 5%");
} 
// Фінальний блок: виконується, якщо всі попередні умови виявилися false (< 500)
else {
    // Виводиться повідомлення про відсутність знижки
    console.log("Знижка не передбачена");
}


// ------------------------------------------
// Завдання 3: Тернарний доступ
// ------------------------------------------
// Виводимо заголовок третього завдання
console.log("\n--- Завдання 3: Тернарний доступ ---");

// Оголошуємо булеву змінну isLoggedIn (true — залогінений, false — ні)
let isLoggedIn = true; 

// Тернарний оператор має синтаксис: умова ? значення_якщо_true : значення_якщо_false
// Якщо isLoggedIn === true -> вибирається "Вітаємо на сайті!"
// Якщо isLoggedIn === false -> вибирається "Будь ласка, увійдіть у систему"
let message = isLoggedIn ? "Вітаємо на сайті!" : "Будь ласка, увійдіть у систему";

// Виводимо збережене у змінній message значення в консоль
console.log(message);