console.log("\n=== Завдання 5: Масив об'єктів, reduce та sort ===");

// 1. Масив об'єктів (кожен елемент масиву є окремим об'єктом товару)
const cart = [
    { title: "Mouse", price: 500, quantity: 2 },
    { title: "Keyboard", price: 1200, quantity: 1 },
    { title: "Monitor", price: 6000, quantity: 1 }
];

// 2. reduce зводить масив до одного числа: acc накопичує суму, 0 — початкове значення acc
const totalCartCost = cart.reduce((acc, item) => acc + item.price * item.quantity, 0);
console.log("Загальна вартість кошика:", totalCartCost, "грн");

// 3. map перетворює масив об'єктів у масив рядків (дістаємо лише поле title)
const productTitles = cart.map(item => item.title);
console.log("Назви товарів:", productTitles);

// 4. sort змінює порядок елементів у масиві (b.price - a.price сортує від більшого до меншого)
cart.sort((a, b) => b.price - a.price);
console.log("Товари за спаданням ціни:", cart.map(item => item.title));

// 5. Сортування чисел без функції порівняння та з нею
const rawNumbers1 = [5, 25, 100, 1, 10];
const rawNumbers2 = [5, 25, 100, 1, 10];

// Пояснення: без функції порівняння sort() перетворює числа на рядки і порівнює їх
// посимвольно як текст ('1' < '10' < '100' < '25' < '5'), тому 100 іде перед 25.
console.log("Сортування без функції порівняння:", rawNumbers1.sort());
console.log("Правильне числове сортування:", rawNumbers2.sort((a, b) => a - b)); // a - b сортує за зростанням


