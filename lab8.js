// ЗАВДАННЯ 4: Методи map, filter, find, some, every
// ============================================================================

console.log("\n=== Завдання 4: Методи map, filter, find, some, every ===");

// 1. Початковий масив цін (усі методи нижче не змінюють його)
const prices = [120, 45, 300, 80, 15, 210];

// 2. map створює новий масив тієї ж довжини, змінюючи кожен елемент за формулою
const discounted = prices.map(price => price * 0.9); // множимо на 0.9, щоб відняти 10%
console.log("Ціни зі знижкою 10% (map):", discounted);

// 3. filter створює новий масив лише з тих елементів, для яких умова повернула true
const expensive = prices.filter(price => price > 100);
console.log("Ціни більші за 100 (filter):", expensive);

// 4. find шукає перший підходящий елемент (або undefined), findIndex — його індекс (або -1)
const firstCheap = prices.find(price => price < 50);
const firstCheapIndex = prices.findIndex(price => price < 50);
console.log(`Перша ціна < 50: ${firstCheap} (індекс: ${firstCheapIndex})`);

// 5. some перевіряє, чи підходить ХОЧА Б ОДИН елемент; every — чи підходять УСІ елементи
const hasOver250 = prices.some(price => price > 250);
const allOver10 = prices.every(price => price > 10);
console.log("Чи є ціна > 250 (some):", hasOver250);
console.log("Чи всі ціни > 10 (every):", allOver10);

// 6. Переконуємось, що вихідний масив залишився незмінним
console.log("Оригінальний масив prices без змін:", prices);


