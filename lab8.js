console.log("\n=== Завдання 3: Перебір масиву ===");

// 1. Масив температур за 7 днів тижня
const temperatures = [18, 21, 19, 25, 30, 27, 22];

// 2. Класичний цикл for — зручний, коли потрібні індекси від 0 до length - 1
let tempSum = 0; // змінна-накопичувач для суми
for (let i = 0; i < temperatures.length; i++) {
    tempSum += temperatures[i]; // додаємо кожну температуру до суми
}
const averageTemp = tempSum / temperatures.length; // середнє = сума / кількість елементів
console.log(`Сума температур: ${tempSum}°C, середня температура: ${averageTemp.toFixed(1)}°C`);

// 3. Цикл for...of — перебирає одразу значення елементів без індексів
let maxTemp = temperatures[0]; // припускаємо, що перший елемент — найбільший
let minTemp = temperatures[0]; // припускаємо, що перший елемент — найменший
for (const temp of temperatures) {
    if (temp > maxTemp) {
        maxTemp = temp; // оновлюємо максимум, якщо знайшли більше число
    }
    if (temp < minTemp) {
        minTemp = temp; // оновлюємо мінімум, якщо знайшли менше число
    }
}
console.log(`Максимальна температура: ${maxTemp}°C, мінімальна: ${minTemp}°C`);

// 4. Метод forEach викликає функцію для кожного елемента (передає значення та його індекс)
console.log("Температура по днях:");
temperatures.forEach((temp, index) => {
    // Тернарний оператор: якщо температура >= 25, додаємо позначку "(спекотно)", інакше — порожній рядок
    const hotLabel = temp >= 25 ? " (спекотно)" : "";
    console.log(`День ${index + 1}: ${temp}°C${hotLabel}`); // index + 1, щоб дні рахувались з 1, а не з 0
});


