console.log("=== Завдання 1: Базові маніпуляції з масивом ===");

// 1. Створюємо масив (нумерація елементів завжди починається з 0)
const books = ["Кобзар", "Тіні забутих предків", "Тигролови", "1984"];

// 2. Виводимо перший елемент, останній (двома способами) і кількість елементів
console.log("Перша книга:", books[0]);                         // індекс 0 — завжди перший елемент
console.log("Остання книга (length - 1):", books[books.length - 1]); // довжина 4 мінус 1 = індекс 3
console.log("Остання книга (at(-1)):", books.at(-1));          // від'ємний індекс рахує з кінця масиву
console.log("Початкова довжина масиву:", books.length);        // .length повертає кількість елементів

// 3. Змінюємо другий елемент (він має індекс 1) на нову назву
books[1] = "Лісова пісня";

// 4. Додаємо елементи: push — у кінець масиву, unshift — на початок
books.push("Місто");
books.unshift("Захар Беркут");

// 5. Видаляємо елементи: pop — останній, shift — перший (обидва повертають видалене значення)
const removedLastBook = books.pop();
const removedFirstBook = books.shift();
console.log("Видалена остання книга:", removedLastBook);
console.log("Видалена перша книга:", removedFirstBook);

// 6. Виводимо фінальний масив і його нову довжину
console.log("Фінальний масив books:", books);
console.log("Фінальна довжина масиву:", books.length);


// ============================================================================
// ЗАВДАННЯ 2: Методи slice, splice, concat, indexOf, includes, join
// ============================================================================

console.log("\n=== Завдання 2: Методи slice, splice, concat, indexOf, includes, join ===");

// 1. Створюємо початковий числовий масив
const numbers = [10, 20, 30, 40, 50, 60];

// 2. slice копіює частину масиву в новий масив, не змінюючи оригінал (кінцевий індекс не входить)
console.log("Елементи з індексами 1..3:", numbers.slice(1, 4)); // бере індекси 1, 2, 3 (4 не входить)
console.log("Останні два елементи:", numbers.slice(-2));        // -2 означає два елементи з кінця
console.log("Оригінальний масив не змінився:", numbers);

// 3. splice змінює сам масив: з індексу 2 видаляє 2 елементи і на їх місце вставляє нові
const removedNumbers = numbers.splice(2, 2, 99, 98, 97);
console.log("Видалені елементи (splice):", removedNumbers);     // повертає масив вирізаних чисел [30, 40]
console.log("Масив numbers після splice:", numbers);

// 4. Об'єднання масивів у новий (оригінали не змінюються)
const extra = [1, 2, 3];
const mergedConcat = numbers.concat(extra);  // класичний метод об'єднання масивів
const mergedSpread = [...numbers, ...extra]; // сучасний спосіб: оператор ... розгортає елементи
console.log("Об'єднання через concat:", mergedConcat);
console.log("Об'єднання через spread (...):", mergedSpread);

// 5. Пошук елементів у масиві
console.log("Чи є число 99 (includes):", numbers.includes(99));    // повертає true або false
console.log("Індекс числа 60 (indexOf):", numbers.indexOf(60));    // повертає позицію елемента в масиві
// Пояснення: метод indexOf повертає -1, коли шуканого елемента немає в масиві
console.log("Індекс числа 1000 (indexOf):", numbers.indexOf(1000));

// 6. join склеює всі елементи масиву в один рядок через вказаний роздільник
console.log("Масив у вигляді рядка:", numbers.join(" | "));


