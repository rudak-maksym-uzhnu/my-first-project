console.log("\n=== Завдання 6: Посилання та двовимірні масиви ===");

// 1. Копіювання за посиланням (Reference Type)
const original = [1, 2, 3];
const link = original; // копіюється не сам масив, а адреса в оперативній пам'яті

// 2. Змінюємо масив через змінну link
link.push(4);
// Пояснення: оскільки масив — це об'єкт, обидві змінні (original і link) посилаються на одну
// й ту саму ділянку пам'яті, тому зміна через одну змінну відображається в іншій.
console.log("original після link.push(4):", original);
console.log("link:", link);

// 3. Створюємо незалежну поверхневу копію через оператор розгортання [...]
const copy = [...original];
copy[0] = 100; // зміна в copy вже не зачіпає original
console.log("Незалежна копія copy:", copy);
console.log("original залишився без змін:", original);

// 4. Двовимірний масив (матриця 3x3 — масив, елементами якого є інші масиви)
const matrix = [
    [1, 2, 3], // рядок з індексом 0
    [4, 5, 6], // рядок з індексом 1
    [7, 8, 9]  // рядок з індексом 2
];
// Перший індекс [2] — номер рядка, другий індекс [0] — номер стовпця
console.log("Елемент matrix[2][0]:", matrix[2][0]);

// 5. Вкладені цикли: зовнішній (i) іде по рядках, внутрішній (j) — по стовпцях
let mainDiagonalSum = 0;
console.log("Усі елементи матриці:");
for (let i = 0; i < matrix.length; i++) {
    for (let j = 0; j < matrix[i].length; j++) {
        console.log(`matrix[${i}][${j}] = ${matrix[i][j]}`);
    }
    // На головній діагоналі індекс рядка дорівнює індексу стовпця: [0][0], [1][1], [2][2]
    mainDiagonalSum += matrix[i][i];
}
console.log("Сума елементів головної діагоналі:", mainDiagonalSum);

// 6. structuredClone створює повну (глибоку) копію разом із усіма вкладеними масивами
const deepMatrixCopy = structuredClone(matrix);
deepMatrixCopy[1][1] = 999; // змінюємо центральний елемент у копії
console.log("Змінений елемент у глибокій копії deepMatrixCopy[1][1]:", deepMatrixCopy[1][1]);
console.log("Оригінальна матриця matrix[1][1] не змінилася:", matrix[1][1]);