// ============================================================================
// ЗАВДАННЯ 1: Комбіновані логічні оператори (&& та ||)
// ============================================================================

// Виводимо заголовок завдання 1 у консоль для чіткого структурування виводу
console.log("=== Завдання 1 ===");

// Оголошуємо змінну score за допомогою ключового слова let та задаємо числове значення 75
let score = 75;

// Перевіряємо складену логічну умову за допомогою конструкції if:
// 1. (score >= 50 && score <= 100) — логічне "І" (&&) повертає true, тільки якщо ОБИДВІ умови є істинними (діапазон [50; 100]).
// 2. || score === 10 — логічне "АБО" (||) повертає true, якщо істинна хоча б одна з двох частин (діапазон АБО рівність 10).
if ((score >= 50 && score <= 100) || score === 10) {
    // Якщо вся підсумкова умова повертає true, виконується цей блок коду
    console.log("Умова виконана");
} else {
    // Якщо жодна з умов не справдилася (результат false), управління переходить у блок else
    console.log("Умова не виконана");
}


// ============================================================================
// ЗАВДАННЯ 2: Керування циклом for за допомогою break та continue
// ============================================================================

// Виводимо розділовий заголовок у консоль (\n створює новий рядок для відступу)
console.log("\n=== Завдання 2 ===");

// Ініціалізуємо цикл for зі стандартним синтаксисом:
// - let i = 1: оголошуємо змінну-лічильник i та задаємо початкове значення 1;
// - i <= 15: умова продовження циклу (ітерації тривають, поки i не перевищує 15);
// - i++: крок циклу (інкремент, збільшує значення i на 1 після кожної ітерації).
for (let i = 1; i <= 15; i++) {

    // Перевіряємо першу умову: якщо поточне значення i строго дорівнює 13 (оператор === перевіряє значення та тип)
    if (i === 13) {
        // Оператор break повністю перериває та завершує виконання циклу for
        break;
    }

    // Перевіряємо другу умову: використання оператора остачі від ділення (%)
    // Якщо i % 3 === 0, це означає, що число ділиться на 3 без залишку (кратне 3)
    if (i % 3 === 0) {
        // Оператор continue достроково завершує ПОТОЧНУ ітерацію та переходить до наступного кроку циклу
        continue;
    }

    // Виводимо значення i в консоль, якщо воно успішно пройшло обидві перевірки
    console.log(i);
}


// ============================================================================
// ЗАВДАННЯ 3: Цикли перебору для масивів (for...of) та об'єктів (for...in)
// ============================================================================

// Виводимо заголовок для Завдання 3
console.log("\n=== Завдання 3 ===");

// ----------------------------------------------------------------------------
// Частина 1: Перебір масиву за допомогою циклу for...of
// ----------------------------------------------------------------------------

// Оголошуємо константний масив myColors (const) з 4 елементами строкового типу
const myColors = ["Червоний", "Чорний", "Зелений", "Білий"];

// Виводимо підзаголовок для списку кольорів
console.log("--- Список кольорів (for...of) ---");

// Синтаксис for...of призначений для послідовного перебору ЗНАЧЕНЬ ітерованих об'єктів (масивів)
// На кожному кроці змінна color отримує значення чергового елемента масиву
for (const color of myColors) {
    // Виводимо поточний колір у консоль
    console.log(color);
}

// ----------------------------------------------------------------------------
// Частина 2: Перебір властивостей об'єкта за допомогою циклу for...in
// ----------------------------------------------------------------------------

// Створюємо об'єкт laptop з трьома властивостями (бренд Lenovo Legion, 32 ГБ RAM та наявність SSD)
const laptop = {
    brand: "Lenovo Legion", // Поле brand: рядок зі значенням "Lenovo Legion"
    ram: 32,                // Поле ram: числове значення 32
    isSSD: true             // Поле isSSD: булеве значення true
};

// Виводимо підзаголовок для характеристик ноутбука
console.log("\n--- Характеристики ноутбука (for...in) ---");

// Синтаксис for...in використовується для перебору КЛЮЧІВ (назв властивостей) об'єкта
// Змінна key на кожній ітерації приймає рядок з назвою ключа ("brand", "ram", "isSSD")
for (const key in laptop) {
    // Використовуємо шаблонний рядок (template literal) із зворотними лапками ``
    // ${key} підставляє назву ключа, а ${laptop[key]} отримає динамічне значення за цим ключем
    console.log(`Ключ: ${key}, Значення: ${laptop[key]}`);
}