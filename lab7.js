console.log("\n=== Завдання 5: Перевірка роботи посилань та методів Object ===");

// 1. Створюємо початковий об'єкт
const originalUser = {
    login: "admin",
    role: "viewer"
};

// 2. Копіюємо посилання на об'єкт у нову змінну adminUser
const adminUser = originalUser;

// 3. Змінюємо властивість role через змінну adminUser
adminUser.role = "superadmin";

// Пояснення: Об'єкти в JavaScript є посилальним типом даних (Reference Type).
// При присвоєнні `const adminUser = originalUser` скопіювався не сам об'єкт,
// а лише адреса (посилання) на ту саму ділянку оперативної пам'яті.
// Тому обидві змінні вказують на один і той самий об'єкт, і зміна через одну
// автоматично відображається в іншій.
console.log("originalUser:", originalUser); // { login: 'admin', role: 'superadmin' }
console.log("adminUser:", adminUser);       // { login: 'admin', role: 'superadmin' }

// 4. Використовуємо вбудовані статичні методи конструктора Object
console.log("Ключі (Object.keys):", Object.keys(originalUser));
console.log("Значення (Object.values):", Object.values(originalUser));
console.log("Пари [ключ, значення] (Object.entries):", Object.entries(originalUser));