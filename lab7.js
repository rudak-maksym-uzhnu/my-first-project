console.log("\n=== Завдання 3: Вкладені структури та перебір ===");

// 1. Створюємо об'єкт company із масивом та багаторівневою вкладеністю
const company = {
    title: "TechVision Ukraine",
    departments: ["Розробка", "Тестування", "Дизайн"], // масив усередині об'єкта
    office: {                                          // вкладений об'єкт 1-го рівня
        country: "Україна",
        city: "Львів",
        coordinates: {                                 // вкладений об'єкт 2-го рівня
            lat: 49.8397,
            lng: 24.0297
        }
    }
};

// 2. Виводимо масив departments через крапку
console.log("Відділи компанії:", company.departments);

// 3. Перебираємо ключі вкладеного об'єкта company.office за допомогою циклу for...in
console.log("Властивості об'єкта company.office:");
for (let key in company.office) {
    // key — назва поточного ключа (наприклад, 'country'), company.office[key] — його значення
    console.log(`${key} : ${company.office[key]}`);
}


