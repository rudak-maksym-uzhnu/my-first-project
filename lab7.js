// 1. Створюємо об'єкт-словник із курсами валют
const currencyRates = {
    usd: 41.5,
    eur: 45.0,
    pln: 10.5
};

// 2. Зберігаємо назву потрібного ключа у змінну
const selectedCurrency = "eur";

// 3. Динамічно дістаємо курс через квадратні дужки currencyRates[selectedCurrency]
// (якби написали через крапку currencyRates.selectedCurrency, отримали б undefined)
const convertedAmount = currencyRates[selectedCurrency] * 100;

// Виводимо результат через шаблонний рядок (зворотні лапки `` та підстановка ${...})
console.log(`100 ${selectedCurrency.toUpperCase()} за курсом ${currencyRates[selectedCurrency]} = ${convertedAmount} грн`);


