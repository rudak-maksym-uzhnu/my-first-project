console.log("\n=== Завдання 4: Створення та виклик методів об'єкта ===");

// 1. Створюємо об'єкт smartPhone із трьома різними способами запису методів
const smartPhone = {
    brand: "Apple iPhone",
    battery: 85,

    // Спосіб 1: Класичний функціональний вираз (Function Expression)
    call: function() {
        console.log("Йде виклик...");
        return "Статус: на лінії";
    },

    // Спосіб 2: Стрілкова функція (Arrow Function) — без return, просто виконує дію
    charge: () => {
        console.log("Зарядка підключена");
    },

    // Спосіб 3: Скорочений сучасний синтаксис методу (ES6)
    takePhoto() {
        console.log("Фото зроблено");
        return "Файл збережено в галерею";
    }
};

// 2. Викликаємо всі три методи
// Для call та takePhoto виводимо у консоль також те, що вони повертають через return
console.log("Результат call():", smartPhone.call());
smartPhone.charge();
console.log("Результат takePhoto():", smartPhone.takePhoto());


