// Допоміжна стрілкова функція для перевірки, чи є значення валідним числом
const isValidNumber = (val) => typeof val === "number" && !isNaN(val);

// Основна функція safeDivide
function safeDivide(a, b) {
    // 1. Перевірка типу аргументів через допоміжну функцію isValidNumber
    if (!isValidNumber(a) || !isValidNumber(b)) {
        return "Помилка: некоректні дані";
    }

    // 2. Захист від ділення на нуль
    if (b === 0) {
        return "Помилка: ділення на нуль";
    }

    // 3. Успішне обчислення
    return a / b;
}

// Тестування безпечного ділення
console.log("10 / 2:", safeDivide(10, 2));         
console.log("10 / 0:", safeDivide(10, 0));         
console.log("10 / 'abc':", safeDivide(10, "abc")); 