function getFactorial(n) {
    // За визначенням, факторіал 0! = 1
    if (n === 0) return 1;

    let factorial = 1;
    // Цикл for множить числа від 1 до n
    for (let i = 1; i <= n; i++) {
        factorial *= i;
    }
    return factorial;
}

// Тестування функціоналу
console.log("Факторіал 0!:", getFactorial(0));
console.log("Факторіал 5!:", getFactorial(5));
console.log("Факторіал 7!:", getFactorial(7));


