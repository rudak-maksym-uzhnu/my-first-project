function countChar(str, char) {
    let count = 0;
    // Приводимо рядок і шуканий символ до нижнього регістру (без урахування регістру)
    let lowerStr = str.toLowerCase();
    let lowerChar = char.toLowerCase();

    // Перебираємо кожен символ у рядку
    for (let c of lowerStr) {
        if (c === lowerChar) {
            count++;
        }
    }
    return count;
}

// Тестування
console.log("Кількість 'a' у 'JavaScript':", countChar("JavaScript", "a")); 
console.log("Кількість 'o' у 'Hello World':", countChar("Hello World", "o")); 
console.log("Кількість 'л' у 'Лабораторна':", countChar("Лабораторна", "л")); 


