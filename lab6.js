// Функціональний вираз (Function Expression), збережений у константу findMin
const findMin = function(a, b, c) {
    // Використовуємо тернарний оператор для пошуку найменшого числа
    let min = a;
    if (b < min) min = b;
    if (c < min) min = c;
    return min;
};

// Тестування з різними значеннями
console.log("Мінімум з (10, 5, 8):", findMin(10, 5, 8));
console.log("Мінімум з (-3, 0, 15):", findMin(-3, 0, 15));
console.log("Мінімум з (7, 7, 2):", findMin(7, 7, 2));


