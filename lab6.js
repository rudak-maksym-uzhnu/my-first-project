// Параметр discount за замовчуванням дорівнює 10%
function calculateDiscount(price, discount = 10) {
    // Обчислюємо суму знижки та віднімаємо її від початкової ціни
    let finalPrice = price - (price * discount / 100);
    return finalPrice;
}

// Перевірка 1: Без передачі другого аргументу (використовується знижка 10%)
console.log("Ціна 1000 грн (знижка за замовчуванням 10%):", calculateDiscount(1000));

// Перевірка 2: З явно вказаною знижкою 20%
console.log("Ціна 1000 грн (знижка 20%):", calculateDiscount(1000, 20));

// Перевірка 3: Ціна 500 грн та знижка 50%
console.log("Ціна 500 грн (знижка 50%):", calculateDiscount(500, 50));


