// Приймає температуру у градусах Цельсія (celsius) та повертає значення у Фаренгейтах
function celsiusToFahrenheit(celsius) {
    // Формула перерахунку: F = C * 1.8 + 32
    return celsius * 1.8 + 32;
}

// Тестування функції з 3 різними наборами аргументів
console.log("0°C у Фаренгейтах:", celsiusToFahrenheit(0));
console.log("25°C у Фаренгейтах:", celsiusToFahrenheit(25));
console.log("-10°C у Фаренгейтах:", celsiusToFahrenheit(-10));


