function getPositiveNumbers(arr) {
    let positiveArray = [];
    // Проходимо по кожному елементу масиву за допомогою циклу for...of
    for (let num of arr) {
        // Якщо число строго більше 0, додаємо його у новий масив
        if (num > 0) {
            positiveArray.push(num);
        }
    }
    return positiveArray;
}

// Тестування з різними масивами
console.log("Масив 1:", getPositiveNumbers([-5, 3, 0, 12, -8, 7]));
console.log("Масив 2:", getPositiveNumbers([-1, -2, -3]));
console.log("Масив 3:", getPositiveNumbers([10, 20, 0]));


