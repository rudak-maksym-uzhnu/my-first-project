// ------------------------------------------
// 1. Моє резюме (Оголошення змінних)
// ------------------------------------------
// Оголошуємо константу firstName для збереження імені (тип String)
const firstName = "Максим";

// Оголошуємо константу lastName для збереження прізвища (тип String)
const lastName = "Рудак";

// Оголошуємо змінну age через let, оскільки вік з часом змінюється (тип Number)
let age = 19;

// Оголошуємо константу favoriteSubject для улюбленого предмета (тип String)
const favoriteSubject = "Немає";

// Оголошуємо константу isStudent, яка вказує статус студента (булевий тип Boolean: true)
const isStudent = true;


// ------------------------------------------
// 2. Перевірка типів даних
// ------------------------------------------
// Виводимо заголовок розділу перевірки типів у консоль
console.log("--- Типи змінних ---");

// Оператор typeof повертає тип змінної firstName ("string") та виводить його в консоль
console.log(typeof firstName);

// Визначаємо та виводимо тип змінної lastName ("string")
console.log(typeof lastName);

// Визначаємо та виводимо тип змінної age ("number")
console.log(typeof age);

// Визначаємо та виводимо тип змінної favoriteSubject ("string")
console.log(typeof favoriteSubject);

// Визначаємо та виводимо тип змінної isStudent ("boolean")
console.log(typeof isStudent);


// ------------------------------------------
// 3. Математичні операції
// ------------------------------------------
// Створюємо константу myAge та копіюємо в неї значення змінної age
const myAge = age;

// Виконуємо додавання: додаємо 5 років до поточного віку myAge (19 + 5 = 24)
const ageIn5Years = myAge + 5;

// Виводимо заголовок розділу математики із відступом нового рядка (\n)
console.log("\n--- Математика ---");

// Виводимо текстовий пояснювальний рядок та обчислене значення ageIn5Years (24)
console.log("Вік через 5 років:", ageIn5Years);


// ------------------------------------------
// 4. Магія порівняння (Оператори == та ===)
// ------------------------------------------
// Створюємо константу strNum, що містить число як рядок ("100", тип String)
const strNum = "100";

// Створюємо константу num, що містить числове значення (100, тип Number)
const num = 100;

// Нестроге порівняння (==): автоматично приводить "100" до числа 100 і порівнює (повертає true)
const looseComparison = strNum == num;

// Виводимо результат нестрогого порівняння у консоль
console.log("Нестроге порівняння (==):", looseComparison);

// Строге порівняння (===): перевіряє і значення, і тип даних без приведення (повертає false)
const strictComparison = strNum === num;

// Виводимо результат строгого порівняння у консоль
console.log("Строге порівняння (===):", strictComparison);

/*
ПОЯСНЕННЯ:
1. Нестроге порівняння (==) виконує неявне перетворення типів: воно автоматично перетворює рядок "100" на число 100 перед порівнянням, тому 100 == 100 повертає true.
2. Строге порівняння (===) перевіряє і значення, і тип даних без жодного перетворення. Оскільки "100" має тип string (рядок), а 100 — тип number (число), типи не збігаються, і результат повертає false.
*/

// ------------------------------------------
// 5. Шаблонні рядки (Template Literals)
// ------------------------------------------
// Виводимо заголовок розділу шаблонних рядків
console.log("\n--- Шаблонний рядок ---");

// Формуємо підсумковий рядок за допомогою зворотних лапок `` та інтерполяції змінних через ${}
const resultMessage = `Привіт! Мене звати ${firstName} ${lastName}, мені ${myAge} років. Через 5 років мені буде ${ageIn5Years}. І так, я студент: ${isStudent}.`;

// Виводимо сформоване повідомлення resultMessage у консоль
console.log(resultMessage);